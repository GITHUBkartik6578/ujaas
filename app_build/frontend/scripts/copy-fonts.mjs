// Copies the self-hosted Devanagari and Latin web fonts out of the @fontsource packages into public/fonts and writes
// src/styles/fonts.css with @font-face rules (including each subset's unicode-range) that point at those stable addresses.
//   npm run fonts:copy
// Why not import the packages' CSS: their file names are hashed by the bundler, so the fonts cannot be preloaded.
// With stable addresses the fonts every page needs are fetched in parallel with the page, which removes the late
// font swap that shifted the layout (measured with Lighthouse). Both fonts are SIL OFL 1.1; the licence text is copied too.
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

const require = createRequire(import.meta.url);
const here = (p) => new URL(p, import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const PUBLIC = here('../public/fonts/');
mkdirSync(PUBLIC, { recursive: true });

const packages = ['@fontsource/noto-sans-devanagari', '@fontsource/noto-serif-devanagari'];
const weights = [400, 700];
let css = '/* Generated by scripts/copy-fonts.mjs. Do not edit by hand. SIL Open Font License 1.1, see public/fonts/OFL.txt. */\n';
for (const pkg of packages) {
  const root = path.dirname(require.resolve(`${pkg}/package.json`));
  for (const weight of weights) {
    // The combined weight file has one @font-face per subset, each with its unicode-range.
    const source = readFileSync(path.join(root, `${weight}.css`), 'utf8');
    for (const block of source.split('@font-face').slice(1)) {
      const family = block.match(/font-family:\s*'([^']+)'/)?.[1];
      const file = block.match(/files\/([^)]+\.woff2)/)?.[1];
      const range = block.match(/unicode-range:\s*([^;}]+)/)?.[1]?.trim();
      if (!family || !file || !range) throw new Error(`Unexpected font CSS in ${pkg} ${weight}.css`);
      copyFileSync(path.join(root, 'files', file), path.join(PUBLIC, file));
      css += `@font-face {\n  font-family: '${family}';\n  font-style: normal;\n  font-display: swap;\n  font-weight: ${weight};\n  src: url('/fonts/${file}') format('woff2');\n  unicode-range: ${range};\n}\n`;
    }
  }
  const licence = path.join(root, 'LICENSE');
  if (existsSync(licence) && !existsSync(path.join(PUBLIC, 'OFL.txt'))) copyFileSync(licence, path.join(PUBLIC, 'OFL.txt'));
}
writeFileSync(here('../src/styles/fonts.css'), css);
console.log('Fonts copied to public/fonts and src/styles/fonts.css written.');
