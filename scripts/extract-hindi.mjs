// Lists every Hindi string a visitor or editor can see, for the proofreading gate (hindi_content skill).
//   node scripts/extract-hindi.mjs > docs/proofreading-list.md
// It extracts Devanagari text from the front-end and server source. It does NOT check spelling: a Hindi proofreader
// signs the list off, and the sign-off is recorded in docs/hardening-report.md.
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';

const files = execFileSync('git', ['ls-files', '-co', '--exclude-standard', 'app_build'], { encoding: 'utf8' }).split('\n').filter(Boolean)
  .filter((f) => /\.(tsx?|css)$/.test(f) && !/(^|\/)(tests|__tests__|e2e)\//.test(f) && !/src\/seed\//.test(f));
const DEV = /[ऀ-ॿ]/;
const byFile = new Map();
let total = 0;
for (const f of files) {
  const seen = new Set();
  readFileSync(f, 'utf8').split('\n').forEach((line, i) => {
    if (!DEV.test(line)) return;
    // text between quotes, backticks or JSX tags that contains Devanagari
    const parts = [...line.matchAll(/(?:'([^']*)'|"([^"]*)"|`([^`]*)`|>([^<>{}]*)<)/g)].map((m) => m[1] ?? m[2] ?? m[3] ?? m[4]).filter((s) => s && DEV.test(s));
    for (const p of parts) { const t = p.trim(); if (t && !seen.has(t)) { seen.add(t); (byFile.get(f) ?? byFile.set(f, []).get(f)).push({ line: i + 1, text: t }); total++; } }
  });
}
console.log('# UJAAS: Hindi strings for proofreading\n');
console.log(`Generated by \`scripts/extract-hindi.mjs\`. ${total} strings in ${byFile.size} files. This list is **not proofread**: it exists so a Hindi proofreader can review every visible string. Mockup text is never copied here; sample content is excluded.\n`);
console.log('Sign-off: ☐ reviewed by ______________   date ____________\n');
for (const [f, items] of byFile) {
  console.log(`## ${f}\n`);
  for (const it of items) console.log(`- L${it.line}: ${it.text}`);
  console.log('');
}
